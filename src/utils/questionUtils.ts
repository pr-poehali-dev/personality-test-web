// Категории в соответствии с MBTI
export const getMbtiTypeFromResults = (scores: Record<string, number>): string => {
  // Определяем каждую дихотомию на основе полученных баллов
  // E vs I: Экстраверсия против Интроверсии (personality)
  const e_i = scores.personality > 60 ? 'E' : 'I';
  
  // S vs N: Сенсорика против Интуиции (based on anxiety and temperament)
  const s_n = (scores.anxiety > 60 && scores.temperament < 50) ? 'N' : 'S';
  
  // T vs F: Мышление против Чувства (based on irritability and confidence)
  const t_f = (scores.irritability > 60 && scores.confidence > 60) ? 'T' : 'F';
  
  // J vs P: Суждение против Восприятия (based on all factors)
  const j_p = (scores.confidence > 60 && scores.anxiety < 40) ? 'J' : 'P';
  
  return `${e_i}${s_n}${t_f}${j_p}`;
};

